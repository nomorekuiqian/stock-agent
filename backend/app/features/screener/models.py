"""
Screener Pydantic models.
"""

from typing import Any

from pydantic import BaseModel, Field


class FilterRequest(BaseModel):
    strategy: str = Field(
        description=(
            "Filter strategy: hot_sectors / volume_surge / value_discovery / "
            "high_dividend / momentum / oversold_quality / by_sector / custom"
        ),
    )
    sector: str | None = Field(
        default=None,
        description="Optional: limit to a specific sector (e.g. 'Technology')",
    )
    params: dict | None = Field(
        default=None,
        description="Optional: override default strategy parameters",
    )


# ---------------------------------------------------------------------------
# Research Agent models
# ---------------------------------------------------------------------------


class ResearchRequest(BaseModel):
    message: str = Field(
        description="User message or selected option value",
        max_length=500,
    )
    history: list[dict] = Field(
        default_factory=list,
        description="Conversation history [{role, content}]",
        max_length=40,
    )
    accumulated_filters: list[dict] = Field(
        default_factory=list,
        description="Accumulated filter conditions from previous turns",
        max_length=30,
    )
    active_context: dict[str, Any] | None = None
    session_id: str | None = Field(
        default=None,
        max_length=80,
        description=(
            "Durable agent runtime session id. In Phase 1 this is the same "
            "UUID as conversation_id; conversation_id remains a compatibility alias."
        ),
    )
    conversation_id: str | None = Field(
        default=None,
        max_length=80,
        description="Compatibility alias for session_id.",
    )
    turn_id: str | None = Field(
        default=None,
        max_length=120,
        description="Client-generated idempotency key for this user turn.",
    )


class ResearchResult(BaseModel):
    success: bool
    message: str = Field(
        default="",
        description="Agent reply text (plain Chinese)",
    )
    options: list[str] = Field(
        default_factory=list,
        description="Dynamic option chips for user to click (plain Chinese strings)",
    )
    candidates: list[dict] = Field(
        default_factory=list,
        description="Filtered stock results (when filters are active)",
    )
    candidate_count: int = 0
    universe_size: int = 0
    recommendations: list[dict] = Field(
        default_factory=list,
        description="Per-stock recommendation reasons [{symbol, reason}]",
    )
    accumulated_filters: list[dict] = Field(
        default_factory=list,
        description="Current accumulated filter conditions",
    )
    reset_results: bool = Field(
        default=False,
        description="When true, frontend should clear all results (direction change)",
    )
    title: str = Field(
        default="",
        description="Conversation title generated by research agent",
    )
    navigate: dict[str, Any] | None = None
    data_freshness: str | None = None
    is_stale: bool = False


# ---------------------------------------------------------------------------
# Research Conversation models
# ---------------------------------------------------------------------------


class ConversationSummary(BaseModel):
    id: str
    title: str
    message_count: int
    updated_at: str
    is_pinned: bool = False
    pinned_at: str | None = None


class ConversationDetail(BaseModel):
    id: str
    user_id: str
    title: str
    data: dict[str, Any]
    message_count: int
    created_at: str
    updated_at: str
    is_pinned: bool = False
    pinned_at: str | None = None


class ConversationSaveRequest(BaseModel):
    id: str | None = Field(default=None, max_length=80)
    title: str = Field(default="", max_length=50)
    data: dict[str, Any] = Field(
        description="Full conversation state (messages, filters, candidates, etc.)",
    )
    message_count: int = Field(default=0, ge=0)
    touch: bool = Field(
        default=True,
        description=(
            "When false, persist state without advancing updated_at. Used for "
            "UI-only panel state saves so history sorting stays tied to chat turns."
        ),
    )


class ConversationPinRequest(BaseModel):
    is_pinned: bool = Field(
        description="Whether this conversation should be pinned in history.",
    )
    agent_id: str | None = Field(
        default=None,
        max_length=64,
        description="Optional runtime agent id for disambiguating the session.",
    )


class FilterResult(BaseModel):
    success: bool
    strategy: str
    candidates: list[dict]
    candidate_count: int
    universe_size: int
    data_freshness: str | None = None
    is_stale: bool = False
    suggestions: list[dict] = Field(
        default_factory=list,
        description="Smart narrowing suggestions based on result distribution",
    )
